"""Prepare inspectable CDSE openEO jobs without authentication or execution."""
from datetime import datetime, timedelta, timezone
import hashlib
import json
import math
from pathlib import Path

from .catalog import utc, validate_bbox

BACKEND = "https://openeo.dataspace.copernicus.eu/openeo/1.2"


def equals(value):
    return {"process_graph": {"eq": {"process_id": "eq", "arguments": {
        "x": {"from_parameter": "value"}, "y": value}, "result": True}}}


def processing_graph(scene, bbox):
    """Request one acquisition day/pass/orbit; source ID must be checked later.

    CDSE may group acquisitions by day. A narrow timestamp filter does not prove
    identity, so keep the requested STAC scene separate from observed job sources.
    """
    validate_bbox(bbox)
    p = scene["properties"]
    day = utc(p["datetime"]).date()
    orbit = p.get("sat:relative_orbit")
    direction = p.get("sat:orbit_state", "").upper()
    if not isinstance(orbit, int) or orbit <= 0 or direction not in {"ASCENDING", "DESCENDING"}:
        raise ValueError("Known relative orbit and pass direction are required")
    if "VV" not in p.get("sar:polarizations", []) or p.get("sar:instrument_mode") != "IW":
        raise ValueError("This baseline requires IW-mode VV radar")
    west, south, east, north = bbox
    zone = min(60, math.floor(((west+east)/2 + 180) / 6) + 1)
    epsg = (32600 if (south+north)/2 >= 0 else 32700) + zone
    return {
        "load": {"process_id": "load_collection", "arguments": {
            "id": "SENTINEL1_GRD", "spatial_extent": dict(west=west, south=south, east=east, north=north, crs="EPSG:4326"),
            "temporal_extent": [day.isoformat(), (day+timedelta(days=1)).isoformat()], "bands": ["VV"],
            "properties": {"sat:orbit_state": equals(direction), "relativeOrbitNumber": equals(orbit)}}},
        "calibrate": {"process_id": "sar_backscatter", "arguments": {
            "data": {"from_node": "load"}, "coefficient": "sigma0-ellipsoid",
            "elevation_model": "COPERNICUS_30", "noise_removal": True}},
        "grid": {"process_id": "resample_spatial", "arguments": {
            "data": {"from_node": "calibrate"}, "resolution": 10, "projection": epsg, "method": "bilinear"}},
        "save": {"process_id": "save_result", "arguments": {
            "data": {"from_node": "grid"}, "format": "GTiff", "options": {}}, "result": True}}


def prepare(catalog_path, out_dir):
    catalog_path, out = Path(catalog_path), Path(out_dir)
    catalog = json.loads(catalog_path.read_text())
    pair = catalog.get("selected_pair")
    if not pair:
        raise ValueError("No matched radar pair in catalogue")
    if out.exists() and any(out.iterdir()):
        raise ValueError("Preparation directory must be empty")
    graphs = {name: processing_graph(pair[name], catalog["bbox"]) for name in ("before", "after")}
    if graphs["before"]["load"]["arguments"]["properties"] != graphs["after"]["load"]["arguments"]["properties"]:
        raise ValueError("Pair orbit/pass filters must match")
    event = utc(catalog["event_date"]+"T00:00:00Z").date()
    if not (utc(pair["before"]["properties"]["datetime"]).date() < event
            < utc(pair["after"]["properties"]["datetime"]).date()):
        raise ValueError("Observations must bracket event day")
    out.mkdir(parents=True, exist_ok=True)
    request = {"backend": BACKEND, "created_at": datetime.now(timezone.utc).isoformat(),
               "catalog_sha256": hashlib.sha256(catalog_path.read_bytes()).hexdigest(),
               "bbox": catalog["bbox"], "event_date": catalog["event_date"],
               "requested_scenes": {name: pair[name]["id"] for name in graphs},
               "processing_status": "prepared_not_executed", "units": "linear sigma0 power",
               "dem": "COPERNICUS_30", "resolution_m": 10,
               "limitations": ["Calibration and geometric orthorectification; no radiometric terrain flattening.",
                               "No radar shadow/layover mask or speckle filter is generated by this recipe.",
                               "Backend property filtering and actual source identities must be verified in job evidence.",
                               "Returned linear power is not detector-ready dB; co-registration must also be checked."]}
    for name, graph in graphs.items():
        (out/f"{name}.process.json").write_text(json.dumps({"process_graph": graph}, indent=2))
    (out/"request.json").write_text(json.dumps(request, indent=2))
    return request
